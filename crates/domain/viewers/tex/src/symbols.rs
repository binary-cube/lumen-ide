//! The named symbols: Greek letters, operators, relations, arrows, big operators and
//! functions (`\sin`, `\lim`), as the atom each command stands for.

use crate::{Class, Font, Node};

/// The atom `\name` stands for, if it's a symbol.
pub fn symbol(name: &str) -> Option<Node> {
    if let Some(c) = greek(name) {
        let font = if c.is_lowercase() { Font::Italic } else { Font::Roman };
        return Some(Node::Symbol { text: c.to_string(), class: Class::Ord, font });
    }
    if let Some((text, symbol, limits)) = big_operator(name) {
        return Some(Node::BigOp { text: text.to_owned(), limits, symbol });
    }
    let (text, class) = match name {
        // Binary operators.
        "pm" => ("±", Class::Bin),
        "mp" => ("∓", Class::Bin),
        "times" => ("×", Class::Bin),
        "div" => ("÷", Class::Bin),
        "cdot" => ("⋅", Class::Bin),
        "ast" => ("∗", Class::Bin),
        "star" => ("⋆", Class::Bin),
        "circ" => ("∘", Class::Bin),
        "bullet" => ("∙", Class::Bin),
        "oplus" => ("⊕", Class::Bin),
        "ominus" => ("⊖", Class::Bin),
        "otimes" => ("⊗", Class::Bin),
        "odot" => ("⊙", Class::Bin),
        "cup" => ("∪", Class::Bin),
        "cap" => ("∩", Class::Bin),
        "setminus" => ("∖", Class::Bin),
        "wedge" | "land" => ("∧", Class::Bin),
        "vee" | "lor" => ("∨", Class::Bin),
        "dagger" => ("†", Class::Bin),
        // Relations.
        "le" | "leq" => ("≤", Class::Rel),
        "ge" | "geq" => ("≥", Class::Rel),
        "ne" | "neq" => ("≠", Class::Rel),
        "leqslant" => ("⩽", Class::Rel),
        "geqslant" => ("⩾", Class::Rel),
        "ll" => ("≪", Class::Rel),
        "gg" => ("≫", Class::Rel),
        "approx" => ("≈", Class::Rel),
        "equiv" => ("≡", Class::Rel),
        "cong" => ("≅", Class::Rel),
        "sim" => ("∼", Class::Rel),
        "simeq" => ("≃", Class::Rel),
        "propto" => ("∝", Class::Rel),
        "in" => ("∈", Class::Rel),
        "notin" => ("∉", Class::Rel),
        "ni" => ("∋", Class::Rel),
        "subset" => ("⊂", Class::Rel),
        "supset" => ("⊃", Class::Rel),
        "subseteq" => ("⊆", Class::Rel),
        "supseteq" => ("⊇", Class::Rel),
        "mid" => ("∣", Class::Rel),
        "parallel" => ("∥", Class::Rel),
        "perp" => ("⊥", Class::Rel),
        "models" => ("⊨", Class::Rel),
        "vdash" => ("⊢", Class::Rel),
        "prec" => ("≺", Class::Rel),
        "succ" => ("≻", Class::Rel),
        "doteq" => ("≐", Class::Rel),
        "coloneqq" | "coloneq" => ("≔", Class::Rel),
        // Arrows.
        "to" | "rightarrow" => ("→", Class::Rel),
        "gets" | "leftarrow" => ("←", Class::Rel),
        "leftrightarrow" => ("↔", Class::Rel),
        "Rightarrow" | "implies" => ("⇒", Class::Rel),
        "Leftarrow" | "impliedby" => ("⇐", Class::Rel),
        "Leftrightarrow" | "iff" => ("⇔", Class::Rel),
        "mapsto" => ("↦", Class::Rel),
        "longrightarrow" => ("⟶", Class::Rel),
        "longleftarrow" => ("⟵", Class::Rel),
        "Longrightarrow" => ("⟹", Class::Rel),
        "uparrow" => ("↑", Class::Rel),
        "downarrow" => ("↓", Class::Rel),
        "nearrow" => ("↗", Class::Rel),
        "searrow" => ("↘", Class::Rel),
        "hookrightarrow" => ("↪", Class::Rel),
        "rightleftharpoons" => ("⇌", Class::Rel),
        // Ordinary symbols.
        "infty" => ("∞", Class::Ord),
        "partial" => ("∂", Class::Ord),
        "nabla" => ("∇", Class::Ord),
        "forall" => ("∀", Class::Ord),
        "exists" => ("∃", Class::Ord),
        "nexists" => ("∄", Class::Ord),
        "neg" | "lnot" => ("¬", Class::Ord),
        "emptyset" | "varnothing" => ("∅", Class::Ord),
        "angle" => ("∠", Class::Ord),
        "triangle" => ("△", Class::Ord),
        "hbar" => ("ℏ", Class::Ord),
        "ell" => ("ℓ", Class::Ord),
        "Re" => ("ℜ", Class::Ord),
        "Im" => ("ℑ", Class::Ord),
        "aleph" => ("ℵ", Class::Ord),
        "wp" => ("℘", Class::Ord),
        "top" => ("⊤", Class::Ord),
        "bot" => ("⊥", Class::Ord),
        "prime" => ("′", Class::Ord),
        "degree" => ("°", Class::Ord),
        "ldots" | "dots" | "dotsc" | "dotsb" => ("…", Class::Ord),
        "cdots" => ("⋯", Class::Ord),
        "vdots" => ("⋮", Class::Ord),
        "ddots" => ("⋱", Class::Ord),
        "checkmark" => ("✓", Class::Ord),
        "square" | "Box" => ("□", Class::Ord),
        "blacksquare" | "qed" => ("■", Class::Ord),
        "therefore" => ("∴", Class::Rel),
        "because" => ("∵", Class::Rel),
        "surd" => ("√", Class::Ord),
        "{" | "lbrace" => ("{", Class::Open),
        "}" | "rbrace" => ("}", Class::Close),
        "langle" => ("⟨", Class::Open),
        "rangle" => ("⟩", Class::Close),
        "lfloor" => ("⌊", Class::Open),
        "rfloor" => ("⌋", Class::Close),
        "lceil" => ("⌈", Class::Open),
        "rceil" => ("⌉", Class::Close),
        "|" | "Vert" => ("‖", Class::Ord),
        "vert" => ("|", Class::Ord),
        "%" => ("%", Class::Ord),
        "$" => ("$", Class::Ord),
        "#" => ("#", Class::Ord),
        "&" => ("&", Class::Ord),
        "_" => ("_", Class::Ord),
        "backslash" => ("∖", Class::Ord),
        "colon" => (":", Class::Punct),
        _ => return None,
    };
    Some(Node::Symbol { text: text.to_owned(), class, font: Font::Roman })
}

fn greek(name: &str) -> Option<char> {
    Some(match name {
        "alpha" => 'α',
        "beta" => 'β',
        "gamma" => 'γ',
        "delta" => 'δ',
        "epsilon" => 'ϵ',
        "varepsilon" => 'ε',
        "zeta" => 'ζ',
        "eta" => 'η',
        "theta" => 'θ',
        "vartheta" => 'ϑ',
        "iota" => 'ι',
        "kappa" => 'κ',
        "lambda" => 'λ',
        "mu" => 'μ',
        "nu" => 'ν',
        "xi" => 'ξ',
        "omicron" => 'ο',
        "pi" => 'π',
        "varpi" => 'ϖ',
        "rho" => 'ρ',
        "varrho" => 'ϱ',
        "sigma" => 'σ',
        "varsigma" => 'ς',
        "tau" => 'τ',
        "upsilon" => 'υ',
        "phi" => 'ϕ',
        "varphi" => 'φ',
        "chi" => 'χ',
        "psi" => 'ψ',
        "omega" => 'ω',
        "Gamma" => 'Γ',
        "Delta" => 'Δ',
        "Theta" => 'Θ',
        "Lambda" => 'Λ',
        "Xi" => 'Ξ',
        "Pi" => 'Π',
        "Sigma" => 'Σ',
        "Upsilon" => 'Υ',
        "Phi" => 'Φ',
        "Psi" => 'Ψ',
        "Omega" => 'Ω',
        _ => return None,
    })
}

/// A big operator's text, whether it's a symbol (`∑`) or a name (`lim`), and whether its
/// scripts go above and below (in display style).
fn big_operator(name: &str) -> Option<(&'static str, bool, bool)> {
    Some(match name {
        "sum" => ("∑", true, true),
        "prod" => ("∏", true, true),
        "coprod" => ("∐", true, true),
        "bigcup" => ("⋃", true, true),
        "bigcap" => ("⋂", true, true),
        "bigvee" => ("⋁", true, true),
        "bigwedge" => ("⋀", true, true),
        "bigoplus" => ("⨁", true, true),
        "bigotimes" => ("⨂", true, true),
        "int" => ("∫", true, false),
        "iint" => ("∬", true, false),
        "iiint" => ("∭", true, false),
        "oint" => ("∮", true, false),
        "lim" => ("lim", false, true),
        "limsup" => ("lim sup", false, true),
        "liminf" => ("lim inf", false, true),
        "max" => ("max", false, true),
        "min" => ("min", false, true),
        "sup" => ("sup", false, true),
        "inf" => ("inf", false, true),
        "det" => ("det", false, true),
        "gcd" => ("gcd", false, true),
        "Pr" => ("Pr", false, true),
        "argmax" => ("arg max", false, true),
        "argmin" => ("arg min", false, true),
        "sin" | "cos" | "tan" | "cot" | "sec" | "csc" | "sinh" | "cosh" | "tanh" | "coth"
        | "arcsin" | "arccos" | "arctan" | "log" | "ln" | "lg" | "exp" | "arg" | "deg" | "dim"
        | "hom" | "ker" | "mod" | "bmod" => {
            let text: &'static str = match name {
                "sin" => "sin",
                "cos" => "cos",
                "tan" => "tan",
                "cot" => "cot",
                "sec" => "sec",
                "csc" => "csc",
                "sinh" => "sinh",
                "cosh" => "cosh",
                "tanh" => "tanh",
                "coth" => "coth",
                "arcsin" => "arcsin",
                "arccos" => "arccos",
                "arctan" => "arctan",
                "log" => "log",
                "ln" => "ln",
                "lg" => "lg",
                "exp" => "exp",
                "arg" => "arg",
                "deg" => "deg",
                "dim" => "dim",
                "hom" => "hom",
                "ker" => "ker",
                _ => "mod",
            };
            (text, false, false)
        }
        _ => return None,
    })
}
