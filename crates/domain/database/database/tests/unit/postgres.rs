use super::*;
use crate::{Change, ChangeSet, ColumnDef, Generated, KeyKind, SchemaChange, TableRef, Value};

fn column(name: &str, ty: &str) -> ColumnDef {
    ColumnDef::new(name, ty)
}

#[test]
fn versions_are_read_and_shown() {
    assert_eq!(parse_version_num("90624"), Some(90624));
    assert_eq!(parse_version_num(" 170002\n"), Some(170002));
    assert_eq!(parse_version_num("x"), None);
    assert_eq!(version_text(90624), "9.6.24");
    assert_eq!(version_text(170002), "17.2");
    assert!(supports(90500, Feature::OnConflict) && !supports(90499, Feature::OnConflict));
    assert!(!supports(96000, Feature::Identity) && supports(100000, Feature::Identity));
    assert!(supports(120000, Feature::Generated) && !supports(110022, Feature::Generated));
}

#[test]
fn row_estimates_by_version() {
    assert_eq!(estimated_rows(140000, -1.0, 0), None, "never analyzed (14+)");
    assert_eq!(estimated_rows(140000, 0.0, 0), Some(0), "empty, analyzed");
    assert_eq!(estimated_rows(130000, 0.0, 0), None, "unknown before 14");
    assert_eq!(estimated_rows(90600, 1234.4, 10), Some(1234));
}

#[test]
fn literals_read_the_same_on_every_server() {
    let d = Postgres::new(90200);
    assert_eq!(d.literal(&Value::Text("it's".into())).unwrap(), "'it''s'");
    assert_eq!(d.literal(&Value::Text(r"a\b".into())).unwrap(), r"E'a\\b'");
    assert_eq!(d.literal(&Value::Bytes(vec![0xde, 0xad])).unwrap(), "decode('dead', 'hex')");
    assert_eq!(d.literal(&Value::Float(f64::NAN)).unwrap(), "'NaN'::float8");
    assert_eq!(d.literal(&Value::Float(f64::NEG_INFINITY)).unwrap(), "'-Infinity'::float8");
    assert_eq!(d.literal(&Value::Bool(true)).unwrap(), "TRUE");
    assert_eq!(d.quote_identifier("we\"ird").unwrap(), "\"we\"\"ird\"");
}

#[test]
fn numbered_columns_by_version() {
    let mut id = column("id", "bigint");
    id.auto_increment = true;
    id.nullable = false;
    assert_eq!(
        Postgres::new(170000).column_definition(&id).unwrap(),
        "\"id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL"
    );
    assert_eq!(Postgres::new(96000).column_definition(&id).unwrap(), "\"id\" BIGSERIAL NOT NULL");
    let mut small = column("n", "integer");
    small.auto_increment = true;
    assert_eq!(Postgres::default().column_definition(&small).unwrap(), "\"n\" SERIAL");
}

#[test]
fn generated_columns_by_version() {
    let mut total = column("total", "numeric");
    total.generated = Some(Generated { expression: "price * qty".into(), stored: true });
    assert!(Postgres::new(110000).column_definition(&total).is_err());
    assert_eq!(
        Postgres::new(120000).column_definition(&total).unwrap(),
        "\"total\" numeric GENERATED ALWAYS AS (price * qty) STORED"
    );
    total.generated = Some(Generated { expression: "price * qty".into(), stored: false });
    assert!(Postgres::new(170000).column_definition(&total).is_err());
    assert!(Postgres::new(180000).column_definition(&total).is_ok());
}

#[test]
fn changes_and_ddl() {
    let d = Postgres::new(160000);
    let table = TableRef { schema: Some("public".into()), name: "orders".into() };
    let set = ChangeSet {
        table: table.clone(),
        changes: vec![Change::Insert { values: vec![("note".into(), Value::Text("x".into()))] }],
    };
    let mut id = crate::ColumnInfo::new("id", "integer");
    id.in_key = true;
    id.key_position = Some(1);
    let s = crate::Structure {
        table: table.clone(),
        columns: vec![id, crate::ColumnInfo::new("note", "text")],
        ..crate::Structure::default()
    };
    assert_eq!(s.key_kind(), KeyKind::Primary(vec!["id".into()]));
    assert_eq!(
        d.changes_of(&set, Some(&s)).unwrap(),
        vec![
            "INSERT INTO \"public\".\"orders\" (\"note\") VALUES ('x') RETURNING \"id\"".to_owned()
        ]
    );
    let add = SchemaChange::AddColumn { table: table.clone(), column: column("paid", "boolean") };
    assert_eq!(
        d.schema(&add).unwrap(),
        vec!["ALTER TABLE \"public\".\"orders\" ADD COLUMN \"paid\" boolean"]
    );
    let drop = SchemaChange::DropIndex { table, name: "orders_note".into() };
    assert_eq!(d.schema(&drop).unwrap(), vec!["DROP INDEX \"public\".\"orders_note\""]);
    assert_eq!(d.pagination(10, 20), "LIMIT 10 OFFSET 20");
}
