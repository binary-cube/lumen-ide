//! The SQL dialects and their words: our own lists, written from each engine's
//! documentation (the SQL standard's reserved words most used, SQLite's "SQL As Understood
//! By SQLite", PostgreSQL's and MySQL's reference manuals), not copied from other tools.
//! A file tells its dialect by its name; the database modules know a console's from its
//! source.

use std::path::Path;

/// The dialect a file is written in.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum Dialect {
    /// Not told: the standard's words only.
    #[default]
    Standard,
    Sqlite,
    Postgres,
    MySql,
}

impl Dialect {
    pub const ALL: [Dialect; 4] =
        [Dialect::Standard, Dialect::Sqlite, Dialect::Postgres, Dialect::MySql];

    /// Its index in [`Dialect::ALL`].
    pub fn index(self) -> usize {
        self as usize
    }

    /// By the file's name: `.pgsql` / `.psql`, or a dialect before `.sql`
    /// (`schema.sqlite.sql`, `x.pg.sql`, `dump.mysql.sql`); otherwise the standard.
    pub fn of_path(path: &Path) -> Self {
        let name = path.file_name().map(|n| n.to_string_lossy().to_ascii_lowercase());
        let Some(name) = name else { return Self::Standard };
        if name.ends_with(".pgsql") || name.ends_with(".psql") {
            return Self::Postgres;
        }
        let Some(stem) = name.strip_suffix(".sql") else { return Self::Standard };
        match stem.rsplit_once('.').map(|(_, tag)| tag) {
            Some("sqlite" | "sqlite3" | "db") => Self::Sqlite,
            Some("pg" | "pgsql" | "psql" | "postgres" | "postgresql") => Self::Postgres,
            Some("mysql" | "mariadb") => Self::MySql,
            _ => Self::Standard,
        }
    }

    /// The rules its text is read and laid out by (the domain's).
    pub fn flavor(self) -> database::sql::Flavor {
        use database::sql::Flavor;
        match self {
            Self::Standard => Flavor::Generic,
            Self::Sqlite => Flavor::Sqlite,
            Self::Postgres => Flavor::Postgres { version: None },
            Self::MySql => Flavor::MySql,
        }
    }

    /// Its own keywords, beyond the standard's.
    pub fn own_keywords(self) -> &'static [&'static str] {
        match self {
            Self::Standard => &[],
            Self::Sqlite => SQLITE,
            Self::Postgres => POSTGRES,
            Self::MySql => MYSQL,
        }
    }
}

