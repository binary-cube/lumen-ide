//! `cargo xtask web-data`: the editor's own CSS / HTML / JavaScript data, generated from MDN's
//! public-domain data (CC0: `@mdn/browser-compat-data` and `mdn-data`, fetched from npm at
//! generation time): which properties, values, at-rules, selectors, elements, attributes,
//! built-in objects and DOM APIs exist, and whether each is deprecated, experimental or
//! non-standard. The JavaScript / DOM signatures come from TypeScript's `lib.*.d.ts`
//! (Apache-2.0; its license and notice are copied next to the data). Written in the editor's
//! own line format into each language module's `data/`; users need no network connection.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::Value;

use crate::dts::Decls;

const BCD: &str = "@mdn/browser-compat-data";
const MDN_DATA: &str = "mdn-data";
/// TypeScript's declaration files ship in the platform packages (any platform will do).
const TYPESCRIPT: &str = "@typescript/typescript-linux-x64";

pub fn generate(root: &Path) -> Result<String, String> {
    let work = root.join("target").join("web-data");
    std::fs::create_dir_all(&work).map_err(|e| e.to_string())?;
    let (bcd_dir, bcd_version) = fetch(BCD, "CC0-1.0", &work)?;
    let (mdn_dir, mdn_version) = fetch(MDN_DATA, "CC0-1.0", &work)?;
    let (ts_dir, ts_version) = fetch(TYPESCRIPT, "Apache-2.0", &work)?;
    let bcd = read_json(&bcd_dir.join("data.json"))?;
    let css_dir = mdn_dir.join("css");
    let header = |what: &str| {
        format!(
            "# The editor's {what} data, generated by `cargo xtask web-data` (do not edit) from MDN's\n\
             # public-domain (CC0) data: {BCD} {bcd_version}, {MDN_DATA} {mdn_version}.\n\
             # Flags: d = deprecated, x = experimental, n = non-standard.\n"
        )
    };

    let css = css(&bcd, &css_dir)?;
    let html = html(&bcd);
    let js = js(&bcd, &typescript(&ts_dir.join("lib"))?);
    let modules = root.join("crates").join("modules");
    let languages = modules.join("languages");
    let write = |module: &str, file: &str, what: &str, body: &str| -> Result<usize, String> {
        let dir = languages.join(module).join("data");
        std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
        let text = format!("{}{body}", header(what));
        std::fs::write(dir.join(file), &text).map_err(|e| e.to_string())?;
        Ok(body.lines().count())
    };
    let n_css = write("css", "css.data", "CSS", &css)?;
    let n_html = write("html", "html.data", "HTML", &html)?;
    let js = format!(
        "# Signatures from TypeScript {ts_version}'s lib.*.d.ts (Apache-2.0, Microsoft;\n\
         # see TYPESCRIPT-LICENSE.txt and TYPESCRIPT-NOTICE.txt).\n{js}"
    );
    let n_js = write("javascript", "js.data", "JavaScript / DOM", &js)?;
    let data = languages.join("javascript").join("data");
    for (from, to) in
        [("LICENSE", "TYPESCRIPT-LICENSE.txt"), ("NOTICE.txt", "TYPESCRIPT-NOTICE.txt")]
    {
        std::fs::copy(ts_dir.join(from), data.join(to)).map_err(|e| format!("{from}: {e}"))?;
    }
    let htmx = htmx(&work)?;
    let n_htmx = htmx.lines().count();
    let dir = modules.join("frameworks").join("htmx").join("data");
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    std::fs::write(dir.join("htmx.data"), htmx).map_err(|e| e.to_string())?;
    Ok(format!(
        "css {n_css}, html {n_html}, js {n_js}, htmx {n_htmx} records ({BCD} {bcd_version})"
    ))
}

/// htmx's attributes (and elements) for each major version from 2 on — the newest release
/// of each, from the editor data htmx ships (0BSD): `a majors name description`, where
/// `majors` lists the versions having it (`2,4`).
fn htmx(work: &Path) -> Result<String, String> {
    const PACKAGE: &str = "htmx.org";
    let meta = curl(&format!("https://registry.npmjs.org/{PACKAGE}"))?;
    let meta: Value = serde_json::from_slice(&meta).map_err(|e| e.to_string())?;
    let parse = |v: &str| -> Option<Vec<u32>> {
        (!v.contains('-')).then(|| v.split('.').map(|p| p.parse().ok()).collect())?
    };
    // The newest release of each major version.
    let mut newest: BTreeMap<u32, (Vec<u32>, String)> = BTreeMap::new();
    for version in meta["versions"].as_object().into_iter().flat_map(|v| v.keys()) {
        let Some(parts) = parse(version).filter(|p| p.first().is_some_and(|m| *m >= 2)) else {
            continue;
        };
        let entry = newest.entry(parts[0]).or_insert_with(|| (Vec::new(), String::new()));
        if parts > entry.0 {
            *entry = (parts, version.clone());
        }
    }
    // name → (kind, majors, description of the newest).
    let mut found: BTreeMap<String, (char, Vec<u32>, String)> = BTreeMap::new();
    let mut versions = Vec::new();
    for (major, (_, version)) in &newest {
        let (dir, _) = unpack(PACKAGE, &meta["versions"][version], "0BSD|BSD-0-Clause", work)?;
        let Some(file) =
            ["dist/editors/jetbrains/htmx.web-types.json", "editors/jetbrains/htmx.web-types.json"]
                .iter()
                .map(|f| dir.join(f))
                .find(|f| f.exists())
        else {
            continue;
        };
        versions.push(version.clone());
        let types = read_json(&file)?;
        let html = &types["contributions"]["html"];
        for (kind, key) in [('a', "attributes"), ('e', "elements")] {
            for item in html[key].as_array().into_iter().flatten() {
                let Some(name) = item["name"].as_str() else { continue };
                let doc = summary(item["description"].as_str().unwrap_or(""));
                let entry = found
                    .entry(name.to_owned())
                    .or_insert_with(|| (kind, Vec::new(), String::new()));
                entry.1.push(*major);
                if !doc.is_empty() {
                    entry.2 = doc;
                }
            }
        }
    }
    let mut out = format!(
        "# The editor's htmx data, generated by `cargo xtask web-data` (do not edit) from the editor\n\
         # data htmx ships (0BSD): htmx.org {}.\n\
         # a|e  majors  name  description\n",
        versions.join(", ")
    );
    for (name, (kind, majors, doc)) in found {
        let majors: Vec<String> = majors.iter().map(u32::to_string).collect();
        out.push_str(&format!("{kind}\t{}\t{name}\t{doc}\n", majors.join(",")));
    }
    Ok(out)
}

/// The first paragraph of a Markdown description, on one line, without links or markup,
/// at most ~280 characters.
fn summary(markdown: &str) -> String {
    let paragraph = markdown.split("\n\n").next().unwrap_or("");
    let mut text = String::new();
    let mut rest = paragraph;
    // `[label](url)` → `label`.
    while let Some(open) = rest.find('[') {
        text.push_str(&rest[..open]);
        let after = &rest[open + 1..];
        match after.find("](").zip(after.find(')')) {
            Some((close, end)) if close < end => {
                text.push_str(&after[..close]);
                rest = &after[end + 1..];
            }
            _ => {
                text.push('[');
                rest = after;
            }
        }
    }
    text.push_str(rest);
    let text = one_line(&text.replace(['`', '*'], ""));
    if text.chars().count() <= 280 {
        return text;
    }
    let cut: String = text.chars().take(280).collect();
    format!("{}…", cut.rsplit_once(' ').map_or(cut.as_str(), |(head, _)| head))
}

/// Downloads the latest `package` from npm into `work` (once per version). Returns the
/// unpacked `package/` directory and the version.
fn fetch(package: &str, expected: &str, work: &Path) -> Result<(PathBuf, String), String> {
    let meta = curl(&format!("https://registry.npmjs.org/{package}/latest"))?;
    let meta: Value = serde_json::from_slice(&meta).map_err(|e| e.to_string())?;
    unpack(package, &meta, expected, work)
}

/// Unpacks the version described by `meta` (an npm version document) into `work`.
pub(crate) fn unpack(
    package: &str,
    meta: &Value,
    expected: &str,
    work: &Path,
) -> Result<(PathBuf, String), String> {
    let version = meta["version"].as_str().ok_or("no version")?.to_owned();
    let license = meta["license"].as_str().unwrap_or("");
    // `expected` may list spellings of the same license (`0BSD|BSD-0-Clause`).
    if !expected.split('|').any(|e| e == license) {
        return Err(format!("{package}: license is `{license}`, expected {expected}"));
    }
    let tarball = meta["dist"]["tarball"].as_str().ok_or("no tarball")?;
    let dir = work.join(format!("{}-{version}", package.replace(['@', '/'], "_")));
    let unpacked = dir.join("package");
    if !unpacked.exists() {
        std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
        let archive = dir.join("package.tgz");
        std::fs::write(&archive, curl(tarball)?).map_err(|e| e.to_string())?;
        let status = Command::new("tar")
            .arg("-xzf")
            .arg(&archive)
            .arg("-C")
            .arg(&dir)
            .status()
            .map_err(|e| format!("tar: {e}"))?;
        if !status.success() {
            return Err(format!("tar failed for {package}"));
        }
    }
    eprintln!("web-data: {package} {version}");
    Ok((unpacked, version))
}

pub(crate) fn curl(url: &str) -> Result<Vec<u8>, String> {
    let output = Command::new("curl")
        .args(["-fsSL", "--max-time", "120", url])
        .output()
        .map_err(|e| format!("curl: {e}"))?;
    if !output.status.success() {
        return Err(format!("{url}: {}", String::from_utf8_lossy(&output.stderr)));
    }
    Ok(output.stdout)
}

fn read_json(path: &Path) -> Result<Value, String> {
    let text = std::fs::read(path).map_err(|e| format!("{}: {e}", path.display()))?;
    serde_json::from_slice(&text).map_err(|e| format!("{}: {e}", path.display()))
}

/// `d` / `x` / `n` from a BCD `__compat.status`.
fn flags(compat: &Value) -> String {
    let status = &compat["__compat"]["status"];
    let mut out = String::new();
    if status["deprecated"].as_bool() == Some(true) {
        out.push('d');
    }
    if status["experimental"].as_bool() == Some(true) {
        out.push('x');
    }
    if status["standard_track"].as_bool() == Some(false) {
        out.push('n');
    }
    out
}

/// The same from an `mdn-data` status string.
fn mdn_flags(status: Option<&str>) -> &'static str {
    match status {
        Some("obsolete") => "d",
        Some("experimental") => "x",
        Some("nonstandard") => "n",
        _ => "",
    }
}

/// The members of a BCD node (sub-features), without `__compat` and without events /
/// `@@` symbols.
fn members(node: &Value) -> impl Iterator<Item = (&String, &Value)> {
    node.as_object()
        .into_iter()
        .flatten()
        .filter(|(k, _)| !k.starts_with("__") && !k.starts_with("@@") && !k.ends_with("_event"))
}

fn css(bcd: &Value, dir: &Path) -> Result<String, String> {
    let properties = read_json(&dir.join("properties.json"))?;
    let syntaxes = read_json(&dir.join("syntaxes.json"))?;
    let at_rules = read_json(&dir.join("at-rules.json"))?;
    let selectors = read_json(&dir.join("selectors.json"))?;
    let functions = read_json(&dir.join("functions.json"))?;
    let mut out = String::new();
    // Properties: `p name flags syntax` then the keywords they accept: `v name keywords`.
    for (name, p) in properties.as_object().into_iter().flatten() {
        if name.starts_with("--") {
            continue;
        }
        let syntax = p["syntax"].as_str().unwrap_or("");
        let compat = &bcd["css"]["properties"][name.as_str()];
        let mut f = mdn_flags(p["status"].as_str()).to_owned();
        if compat.is_object() {
            f = flags(compat);
        }
        out.push_str(&format!("p\t{name}\t{f}\t{}\n", one_line(syntax)));
        let mut keywords = BTreeSet::new();
        collect_keywords(syntax, &syntaxes, 0, &mut keywords);
        if !keywords.is_empty() {
            let list: Vec<&str> = keywords.iter().map(String::as_str).collect();
            out.push_str(&format!("v\t{name}\t{}\n", list.join(" ")));
        }
    }
    for (name, a) in at_rules.as_object().into_iter().flatten() {
        out.push_str(&format!("@\t{}\t{}\n", name, mdn_flags(a["status"].as_str())));
    }
    for (_, s) in selectors.as_object().into_iter().flatten() {
        let syntax = s["syntax"].as_str().unwrap_or("");
        // `:hover`, `::before`, `:nth-child( <an+b> )` → the name, with its colons.
        if syntax.starts_with(':') {
            let name: String = syntax
                .chars()
                .take_while(|c| *c == ':' || c.is_alphanumeric() || *c == '-')
                .collect();
            let kind = if name.starts_with("::") { "e" } else { "c" };
            out.push_str(&format!("{kind}\t{name}\t{}\n", mdn_flags(s["status"].as_str())));
        }
    }
    for (name, f) in functions.as_object().into_iter().flatten() {
        out.push_str(&format!(
            "f\t{}\t{}\n",
            name.trim_end_matches("()"),
            mdn_flags(f["status"].as_str())
        ));
    }
    Ok(out)
}

/// The keywords a value syntax accepts, following `<type>` references into
/// `syntaxes.json` a few levels deep (`display` → `<display-outside>` → `block | inline…`).
fn collect_keywords(syntax: &str, syntaxes: &Value, depth: usize, out: &mut BTreeSet<String>) {
    if depth > 4 {
        return;
    }
    let mut rest = syntax;
    while !rest.is_empty() {
        let c = rest.chars().next().unwrap_or(' ');
        if c == '<' {
            // `<name>` or `<name [0,∞]>` / `<'property'>`: a reference.
            let end = rest.find('>').map_or(rest.len(), |i| i + 1);
            let inner = rest[1..end.saturating_sub(1)].split_whitespace().next().unwrap_or("");
            if !inner.starts_with('\'')
                && let Some(nested) = syntaxes[inner]["syntax"].as_str()
            {
                collect_keywords(nested, syntaxes, depth + 1, out);
            }
            rest = &rest[end.min(rest.len())..];
        } else if c.is_ascii_alphabetic() || c == '-' {
            let len = rest
                .find(|ch: char| !(ch.is_ascii_alphanumeric() || ch == '-'))
                .unwrap_or(rest.len());
            let word = &rest[..len];
            // A function (`rgb(`) is not a keyword.
            if !rest[len..].starts_with('(') && word.len() > 1 {
                out.insert(word.to_owned());
            }
            rest = &rest[len..];
        } else {
            rest = &rest[c.len_utf8()..];
        }
    }
}

fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn html(bcd: &Value) -> String {
    let mut out = String::new();
    for (name, attribute) in members(&bcd["html"]["global_attributes"]) {
        out.push_str(&format!("a\t*\t{name}\t{}\n", flags(attribute)));
    }
    for (tag, element) in members(&bcd["html"]["elements"]) {
        out.push_str(&format!("e\t{tag}\t{}\n", flags(element)));
        let mut seen = BTreeSet::new();
        for (name, attribute) in members(element) {
            if name.contains(' ') {
                continue;
            }
            // `type_button`: attribute `type` with the value `button`.
            match name.split_once('_') {
                Some((attr, value)) => {
                    if seen.insert(attr.to_owned()) {
                        out.push_str(&format!("a\t{tag}\t{attr}\t\n"));
                    }
                    out.push_str(&format!("v\t{tag}\t{attr}\t{value}\t{}\n", flags(attribute)));
                }
                None => {
                    if seen.insert(name.clone()) {
                        out.push_str(&format!("a\t{tag}\t{name}\t{}\n", flags(attribute)));
                    }
                }
            }
        }
    }
    out
}

/// The declarations of every `lib.*.d.ts` except the web workers' (which redeclare the
/// DOM's names differently) and the script host's.
fn typescript(lib: &Path) -> Result<Decls, String> {
    let mut decls = Decls::default();
    let mut files: Vec<_> = std::fs::read_dir(lib)
        .map_err(|e| format!("{}: {e}", lib.display()))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| {
            let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("");
            name.starts_with("lib.")
                && name.ends_with(".d.ts")
                && !name.starts_with("lib.webworker")
                && !name.starts_with("lib.scripthost")
        })
        .collect();
    files.sort();
    for file in files {
        let text =
            std::fs::read_to_string(&file).map_err(|e| format!("{}: {e}", file.display()))?;
        decls.add(&text);
    }
    Ok(decls)
}

/// The built-in objects and DOM interfaces with their members (MDN), each with its
/// signature when TypeScript declares it: `g name flags sig` (a function's or a
/// constructor's) and `m owner member flags sig` (`(params): type` or `: type`).
fn js(bcd: &Value, decls: &Decls) -> String {
    let mut out = String::new();
    let mut seen: BTreeMap<String, ()> = BTreeMap::new();
    let mut emit = |out: &mut String, owner: &str, node: &Value| {
        if seen.insert(owner.to_owned(), ()).is_some() {
            return;
        }
        let sig = decls.global(owner).filter(|s| s.len() <= 300).unwrap_or_default();
        out.push_str(&format!("g\t{owner}\t{}\t{sig}\n", flags(node)));
        for (member, value) in members(node) {
            if member == owner || member.contains(' ') {
                continue;
            }
            // Very long signatures (unions of every typed array…) help nobody.
            let sig = decls.member(owner, member).filter(|s| s.len() <= 300).unwrap_or_default();
            out.push_str(&format!("m\t{owner}\t{member}\t{}\t{sig}\n", flags(value)));
        }
    };
    for (name, node) in members(&bcd["javascript"]["builtins"]) {
        emit(&mut out, name, node);
    }
    for (name, node) in members(&bcd["api"]) {
        emit(&mut out, name, node);
    }
    out
}
