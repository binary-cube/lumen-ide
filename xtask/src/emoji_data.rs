//! `cargo xtask emoji-data`: the Markdown preview's emoji shortcodes (`:rocket:` → 🚀),
//! generated from GitHub's gemoji database (MIT, fetched at generation time) into the
//! module's `data/emoji.data`: one `alias emoji` per line, sorted by alias. Users need no
//! network connection.

use std::path::Path;

use serde_json::Value;

use crate::web_data::curl;

/// GitHub's own list (the shortcodes GitHub renders).
const SOURCE: &str = "https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json";

pub fn generate(root: &Path) -> Result<String, String> {
    let bytes = curl(SOURCE)?;
    let db: Value = serde_json::from_slice(&bytes).map_err(|e| format!("gemoji: {e}"))?;
    let mut pairs = Vec::new();
    for entry in db.as_array().ok_or("gemoji: not a list")? {
        let Some(emoji) = entry.get("emoji").and_then(Value::as_str) else { continue };
        for alias in entry.get("aliases").and_then(Value::as_array).into_iter().flatten() {
            if let Some(alias) = alias.as_str() {
                pairs.push((alias.to_owned(), emoji.to_owned()));
            }
        }
    }
    pairs.sort();
    pairs.dedup_by(|a, b| a.0 == b.0);
    let mut text = String::from(
        "# The Markdown preview's emoji shortcodes, generated by `cargo xtask emoji-data` (do not\n\
         # edit) from GitHub's gemoji (MIT, Copyright (c) 2019 GitHub, Inc.): `alias emoji`.\n",
    );
    for (alias, emoji) in &pairs {
        text.push_str(alias);
        text.push(' ');
        text.push_str(emoji);
        text.push('\n');
    }
    let dir = root.join("crates/modules/viewers/markdown/data");
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    std::fs::write(dir.join("emoji.data"), text).map_err(|e| e.to_string())?;
    Ok(format!("{} shortcodes", pairs.len()))
}
