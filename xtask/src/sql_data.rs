//! `cargo xtask sql-data`: the SQL language's own data — SQLite's built-in functions, read
//! from `pragma_function_list` of the SQLite compiled into `rusqlite` (the very version and
//! compile options the app runs: the same workspace dependency, the same features). Written
//! in the editor's line format into `crates/modules/languages/sql/data/sqlite.functions`;
//! users need nothing installed. PostgreSQL's come from the connected server (its own
//! version), so none are generated here.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

/// One row of `pragma_function_list`: its name, kind (`s` scalar, `a` aggregate, `w`
/// window) and argument count (`-1`: any number).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FunctionRow {
    pub name: String,
    pub kind: String,
    pub arity: i64,
}

pub fn generate(root: &Path) -> Result<String, String> {
    let db = rusqlite::Connection::open_in_memory().map_err(|e| e.to_string())?;
    let version: String =
        db.query_row("SELECT sqlite_version()", [], |r| r.get(0)).map_err(|e| e.to_string())?;
    let mut statement = db
        .prepare("SELECT name, type, narg FROM pragma_function_list")
        .map_err(|e| e.to_string())?;
    let rows = statement
        .query_map([], |r| Ok(FunctionRow { name: r.get(0)?, kind: r.get(1)?, arity: r.get(2)? }))
        .map_err(|e| e.to_string())?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| e.to_string())?;
    let text = format(&version, &rows);
    let dir = root.join("crates/modules/languages/sql/data");
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    std::fs::write(dir.join("sqlite.functions"), &text).map_err(|e| e.to_string())?;
    let count = text.lines().filter(|l| !l.starts_with('#')).count();
    Ok(format!("{count} SQLite {version} functions"))
}

/// The data file: a header, then one line per function (sorted by name, in capitals as the
/// editor offers SQL's words; SQLite ignores their case):
/// `name<TAB>kinds<TAB>arities`, the kinds and arities each sorted and joined by `,`.
pub fn format(version: &str, rows: &[FunctionRow]) -> String {
    let mut by_name: BTreeMap<String, (BTreeSet<char>, BTreeSet<i64>)> = BTreeMap::new();
    for row in rows {
        let name = row.name.to_ascii_uppercase();
        // Names a statement can't call (none today, but a build option could add some).
        if name.is_empty() || !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
            continue;
        }
        let entry = by_name.entry(name).or_default();
        entry.0.extend(row.kind.chars().next());
        entry.1.insert(row.arity);
    }
    let mut out = format!(
        "# The editor's SQLite functions, generated by `cargo xtask sql-data` (do not edit) from\n\
         # pragma_function_list of SQLite {version} (bundled with rusqlite: the version the app runs).\n\
         # name<TAB>kinds (s scalar, a aggregate, w window)<TAB>argument counts (-1: any number)\n"
    );
    for (name, (kinds, arities)) in by_name {
        let kinds: Vec<String> = kinds.iter().map(char::to_string).collect();
        let arities: Vec<String> = arities.iter().map(i64::to_string).collect();
        out.push_str(&format!("{name}\t{}\t{}\n", kinds.join(","), arities.join(",")));
    }
    out
}

